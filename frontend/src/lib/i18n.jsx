const LangContext = createContext({ lang: "pt", setLang: () => {}, t: (k) => k, locale: "pt-PT" });
function useLang() {
  return useContext(LangContext);
}
const warned = new Set();
function translate(lang, key, vars) {
  let s = STRINGS[lang]?.[key] ?? STRINGS.pt[key];
  if (s === undefined) {
    // Missing key: fall back to the key itself (never crash the UI), but shout in dev
    // so it can't silently ship as raw text like "settings.general" again.
    if (import.meta.env?.DEV && !warned.has(key)) { warned.add(key); console.warn(`[i18n] missing translation key: ${key}`); }
    s = key;
  }
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, String(v)); });
  return s;
}
function LangProvider({ children }) {
  const [lang, setLang] = useState("pt");
  const t = (key, vars) => translate(lang, key, vars);
  const locale = lang === "pt" ? "pt-PT" : "en-US";
  return <LangContext.Provider value={{ lang, setLang, t, locale }}>{children}</LangContext.Provider>;
}


export { LangContext, useLang, translate, LangProvider, STRINGS };
