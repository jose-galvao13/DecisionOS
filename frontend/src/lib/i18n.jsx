const LangContext = createContext({ lang: "pt", setLang: () => {}, t: (k) => k, locale: "pt-PT" });
function useLang() {
  return useContext(LangContext);
}
function translate(lang, key, vars) {
  let s = STRINGS[lang]?.[key] ?? STRINGS.pt[key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, String(v)); });
  return s;
}
function LangProvider({ children }) {
  const [lang, setLang] = useState("pt");
  const t = (key, vars) => translate(lang, key, vars);
  const locale = lang === "pt" ? "pt-PT" : "en-US";
  return <LangContext.Provider value={{ lang, setLang, t, locale }}>{children}</LangContext.Provider>;
}


export { LangContext, useLang, translate, LangProvider };
